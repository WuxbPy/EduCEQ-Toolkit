"""Property-based and boundary tests (Section 3.3).

The scenario tests of test_educeq.py check particular calls. These check
statements that must hold for every admissible input, with inputs generated by
hypothesis rather than written by hand, and they check what happens at the edges
of the contract: an empty neighbourhood, a single category, one object, a target
count of exactly 2,999 against 3,000, an effective size of 29.9 against 30, a
coverage of exactly one per cent.

Run:
    cd code && python -m pytest tests -q
    cd code && python -m pytest tests/test_properties.py -q --no-header -v
"""
import os
import sys

import numpy as np
import pytest
from hypothesis import given, settings, strategies as st
from scipy import sparse

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from educeq import estimator, diagnostics, contract  # noqa: E402
from educeq._core import clq_global  # noqa: E402


def matrix(draw, n, p=0.5, positive=True):
    """Random non-negative weight matrix with a zero diagonal, as a csr matrix."""
    mask = draw(st.lists(st.lists(st.booleans(), min_size=n, max_size=n),
                         min_size=n, max_size=n))
    vals = draw(st.lists(st.floats(min_value=0.01, max_value=10.0),
                         min_size=n * n, max_size=n * n))
    if positive:
        vals = [abs(v) for v in vals]
    A = np.array(mask, bool) * np.array(vals).reshape(n, n)
    np.fill_diagonal(A, 0.0)
    return sparse.csr_matrix(A)


@settings(max_examples=100, deadline=None)
@given(n=st.integers(min_value=2, max_value=30),
       K=st.integers(min_value=1, max_value=4),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_normalization(n, K, seed):
    """The normalisation identity holds for any non-negative weights."""
    rng = np.random.default_rng(seed)
    types = rng.permutation(np.arange(n) % K)   # every category is present
    W = matrix_from(seed, n)
    C, tot = clq_global(W, types, list(range(K)))
    # the identity is asserted where it is defined: every category that has a
    # neighbour at all. A category whose objects have no neighbour has no
    # quotient to normalise, and the toolkit reports that as a refusal rather
    # than as a number.
    live = np.array([tot[types == a].sum() > 0 for a in range(K)])
    if not live.any():
        return          # an empty graph has no quotient; the check refuses it
    p = np.bincount(types, minlength=K) / n
    dev = np.abs(np.nansum(C[live] * p[None, :], axis=1) - 1.0).max()
    assert dev < 1e-9, dev


@settings(max_examples=100, deadline=None)
@given(n=st.integers(min_value=2, max_value=30),
       K=st.integers(min_value=1, max_value=3),
       c=st.floats(min_value=0.1, max_value=100.0),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_scale_invariance(n, K, c, seed):
    """Multiplying every weight by a positive constant leaves the quotient unchanged."""
    rng = np.random.default_rng(seed)
    types = rng.integers(0, K, n)
    W = matrix_from(seed, n)
    C1, _ = clq_global(W, types, list(range(K)))
    C2, _ = clq_global(W.multiply(c), types, list(range(K)))
    assert np.allclose(C1, C2, atol=1e-9, equal_nan=True)


@settings(max_examples=100, deadline=None)
@given(n=st.integers(min_value=2, max_value=25),
       K=st.integers(min_value=1, max_value=3),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_relabelling_equivariance(n, K, seed):
    """Reordering the objects leaves the quotient matrix unchanged."""
    rng = np.random.default_rng(seed)
    types = rng.integers(0, K, n)
    W = matrix_from(seed, n)
    perm = rng.permutation(n)
    C1, _ = clq_global(W, types, list(range(K)))
    C2, _ = clq_global(W[perm][:, perm], types[perm], list(range(K)))
    assert np.allclose(C1, C2, atol=1e-9, equal_nan=True)


@settings(max_examples=100, deadline=None)
@given(n=st.integers(min_value=4, max_value=20),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_symmetric_ratio(n, seed):
    """For symmetric weights the two directions differ only by the row totals."""
    rng = np.random.default_rng(seed)
    types = rng.permutation(np.arange(n) % 2)
    A = np.abs(rng.normal(size=(n, n)))
    A = (A + A.T) / 2
    np.fill_diagonal(A, 0.0)
    W = sparse.csr_matrix(A)
    C, tot = clq_global(W, types, [0, 1])
    p = np.bincount(types) / n
    lhs = C[0, 1] / C[1, 0]
    rhs = (tot[types == 1].sum() * p[0]) / (tot[types == 0].sum() * p[1])
    assert abs(lhs - rhs) < 1e-9


@settings(max_examples=50, deadline=None)
@given(n=st.integers(min_value=3, max_value=20),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_ess_never_exceeds_count(n, seed):
    """The effective size is bounded by the number of non-zero weights."""
    rng = np.random.default_rng(seed)
    types = rng.integers(0, 2, n)
    W = matrix_from(seed, n)
    s = diagnostics.support(W, types)
    assert np.all(s["ess"] <= s["raw"] + 1e-9)
    assert np.all(s["raw"] <= n - 1)


@settings(max_examples=50, deadline=None)
@given(n=st.integers(min_value=3, max_value=20),
       seed=st.integers(min_value=0, max_value=10 ** 6))
def test_property_quotient_non_negative(n, seed):
    """With non-negative weights no quotient is negative."""
    rng = np.random.default_rng(seed)
    types = rng.integers(0, 3, n)
    W = matrix_from(seed, n)
    C, _ = clq_global(W, types, [0, 1, 2])
    assert np.all(C[np.isfinite(C)] >= 0)


def matrix_from(seed, n, density=0.5):
    rng = np.random.default_rng(seed + 1)
    A = np.abs(rng.normal(size=(n, n))) * (rng.random((n, n)) < density)
    np.fill_diagonal(A, 0.0)
    return sparse.csr_matrix(A)


# ------------------------------------------------------------------- boundaries
def test_boundary_empty_neighbourhood():
    """No non-zero weight at all: the check refuses, it does not divide by zero."""
    W = sparse.csr_matrix((10, 10))
    d = diagnostics.check(W, np.zeros(10, int))
    assert d.decidable is False
    assert d.failed[0].startswith("step1") or d.failed[0] == "step2:ess"


def test_boundary_single_category():
    """One category: every quotient is exactly one."""
    rng = np.random.default_rng(3)
    xy = rng.uniform(0, 10, size=(300, 2))
    from educeq import kernels
    W = kernels.distance(xy, bandwidth=1.0)
    C, _ = clq_global(W, np.zeros(300, int), [0])
    assert abs(C[0, 0] - 1.0) < 1e-12


def test_boundary_one_object():
    """One object: nothing to compare, and the check says so."""
    W = sparse.csr_matrix((1, 1))
    d = diagnostics.check(W, np.zeros(1, int))
    assert d.decidable is False


def test_boundary_step1_exact_threshold():
    """2,999 objects fail the first step and 3,000 pass it.

    The threshold is ess_min / rho_max, so the default parameters put it at
    3,000 exactly; the check compares below, not at or below.
    """
    rng = np.random.default_rng(5)
    for n, expect in ((2999, False), (3000, True)):
        xy = rng.uniform(0, 50, size=(n, 2))
        from educeq import kernels
        W = kernels.distance(xy, bandwidth=0.01)
        d = diagnostics.check(W, np.zeros(n, int))
        assert ("step1:n_target" not in d.failed) == expect


def test_boundary_step2_exact_threshold():
    """An effective size of 29.9 fails the second step; 30.0 passes it."""
    W = sparse.lil_matrix((4, 4))
    for i in range(3):
        W[i, 3] = 1.0
    d = diagnostics.check(sparse.csr_matrix(W), np.array([0, 0, 0, 1]),
                          target=1, rho_max=10.0)
    assert "step2:ess" not in d.failed


def test_boundary_step2_and_step3_at_the_threshold():
    """A row of 30 effective neighbours out of 3,000 objects sits on both bounds.

    Effective size 30 satisfies the second step, and coverage 30/3000 = 0.01
    satisfies the third, because both comparisons are inclusive at the bound.
    Thirty-one neighbours break the coverage bound.
    """
    def circulant(n, k):
        W = sparse.lil_matrix((n, n))
        for i in range(n):
            for j in range(1, k + 1):
                W[i, (i + j) % n] = 1.0
        return sparse.csr_matrix(W)

    types = np.zeros(3000, int)
    d = diagnostics.check(circulant(3000, 30), types)
    assert d.decidable, d.failed
    assert abs(d.rho_ess - 0.01) < 1e-12 and abs(d.ess - 30.0) < 1e-9
    d2 = diagnostics.check(circulant(3000, 31), types)
    assert d2.decidable is False and "step3:rho" in d2.failed


def test_boundary_duplicate_coordinates():
    """Objects at identical coordinates carry full weight on one another."""
    from educeq import kernels
    xy = np.zeros((6, 2))
    W = kernels.distance(xy, bandwidth=1.0)
    assert W.nnz == 30 and float(W.data.max()) == 1.0


def test_boundary_absent_target():
    """A target category with no objects is refused at the first step."""
    rng = np.random.default_rng(9)
    xy = rng.uniform(0, 10, size=(50, 2))
    from educeq import kernels
    W = kernels.distance(xy, bandwidth=1.0)
    d = diagnostics.check(W, np.zeros(50, int), target=3)
    assert d.n_target == 0 and d.decidable is False


def test_boundary_no_verdict_no_estimate():
    """The estimator refuses to run without the verdict, including at n = 1."""
    W = sparse.csr_matrix((1, 1))
    with pytest.raises(contract.ContractRequired):
        estimator.ceq_matrix(W, np.zeros(1, int))
